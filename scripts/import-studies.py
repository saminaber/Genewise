#!/usr/bin/env python3
"""Merge public, publication-filtered GWAS records; never process personal DNA."""
import json,re,subprocess,sys,urllib.parse,urllib.request
from datetime import datetime,timezone
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
STUDIES={'30846698':'Sleep','32059762':'Nutrition','25288136':'Caffeine','30223776':'Taste'}
raw=subprocess.check_output(['node','--input-type=module','-e',"import {catalog,catalogMetadata} from './src/lib/catalog.js';console.log(JSON.stringify({catalog,catalogMetadata}));"],cwd=ROOT,text=True)
snapshot=json.loads(raw);index={m['rsid']:m for m in snapshot['catalog']};sources=[]
for pmid,category in STUDIES.items():
 cache=ROOT/'.cache/studies'/(pmid+'.json')
 url='https://www.ebi.ac.uk/gwas/rest/api/v2/associations?'+urllib.parse.urlencode({'pubmed_id':pmid,'size':500})
 if '--fetch' in sys.argv:
  try:
   with urllib.request.urlopen(url,timeout=18) as r:data=json.load(r)
   cache.parent.mkdir(parents=True,exist_ok=True);cache.write_text(json.dumps({'url':url,'data':data}))
  except Exception as error:print('Fetch unavailable:',pmid,str(error),flush=True)
 if not cache.exists():sources.append({'pubmedId':pmid,'url':url,'warning':'No cached study response'});continue
 response=json.loads(cache.read_text());data=response['data'];accepted=0
 for a in data.get('_embedded',{}).get('associations',[]):
  # Verify both the requested publication and each usable association.
  if str(a.get('pubmed_id'))!=pmid or a.get('multi_snp_haplotype') or a.get('snp_interaction'):continue
  variants=a.get('snp_allele',[]);p=a.get('p_value');study=a.get('accession_id','')
  if len(variants)!=1 or not re.fullmatch(r'rs\d+',variants[0].get('rs_id','')) or not re.fullmatch(r'GCST\d+',study):continue
  if not isinstance(p,(float,int)) or not 0<p<=5e-8:continue
  rsid=variants[0]['rs_id'];traits=[t['efo_trait'] for t in a.get('efo_traits',[]) if t.get('efo_trait')]
  label=', '.join(traits) or '; '.join(a.get('reported_trait',[])) or 'Study trait'
  evidence={'rsid':rsid,'category':category,'trait':label,'associationId':a['association_id'],'study':study,'pmid':pmid,'pValue':p,'mappedGenes':a.get('mapped_genes',[]),'reportedTraits':a.get('reported_trait',[]),'locations':a.get('locations',[])}
  marker=index.setdefault(rsid,{'rsid':rsid,'category':category,'categories':[],'traits':[],'evidence':[]})
  if category not in marker['categories']:marker['categories'].append(category)
  if label not in marker['traits']:marker['traits'].append(label)
  if not any(e['associationId']==evidence['associationId'] for e in marker['evidence']):marker['evidence'].append(evidence)
  accepted+=1
 sources.append({'pubmedId':pmid,'category':category,'url':response['url'],'acceptedAssociations':accepted,'returnedAssociations':len(data.get('_embedded',{}).get('associations',[])),'totalAvailable':data.get('page',{}).get('totalElements',0)})
 print(pmid,category,'eligible records:',accepted,flush=True)
markers=[]
for marker in index.values():
 evidence=sorted(marker['evidence'],key=lambda e:e['pValue']);genes=sorted({g for e in evidence for g in e['mappedGenes']})
 marker.update(title=marker['traits'][0].capitalize(),gene=', '.join(genes) or 'No mapped gene reported',context='The GWAS Catalog records a population-level association with '+', '.join(marker['traits'])+'. Mapped genes are annotations, not proof of a causal mechanism. This entry does not predict an individual trait.',paper='https://pubmed.ncbi.nlm.nih.gov/'+evidence[0]['pmid']+'/',source='https://www.ebi.ac.uk/gwas/variants/'+marker['rsid'],evidence=evidence)
 markers.append(marker)
markers.sort(key=lambda m:(m['category'],m['rsid']))
metadata=snapshot['catalogMetadata'];metadata.update(retrievedAt=datetime.now(timezone.utc).isoformat(),markerCount=len(markers),associationCount=sum(len(m['evidence']) for m in markers),studyImports=sources)
metadata['selection']='Union of prior bounded trait snapshots and publication-filtered study imports. Single-rsID non-interaction associations with p <= 5e-8 and verified publication/study identifiers. Not a comprehensive catalog or a validated prediction model.'
(ROOT/'src/lib/catalog.js').write_text('// Generated by reference-import scripts; do not hand-edit.\nexport const catalog = '+json.dumps(markers,indent=2)+';\nexport const catalogMetadata = '+json.dumps(metadata,indent=2)+';\n')
(ROOT/'data/catalog-provenance.json').write_text(json.dumps(metadata,indent=2)+'\n')
print('Imported catalog:',len(markers),'markers;',metadata['associationCount'],'associations')
